"""Compare representations: overall, per density bucket, and for significance.

    python -m src.eval.compare
    python -m src.eval.compare --out reports/sprint5_results.md

Reads data/labeled/predictions.csv (written by src.models.run_cv) and answers
the three hypotheses directly:

  H1  does the transformer win overall?
  H2  does its margin shrink as density rises?
  H3  does fastText degrade less than TF-IDF on heavily mixed text?

Three things this reports that a bare accuracy table would hide:

**A majority-class floor per bucket.** If `high` is 70% one class, a model
scoring 0.70 accuracy there has learned nothing. Every bucket is shown against
its own floor.

**McNemar with Holm-Bonferroni.** The comparisons are paired on the same items
and there are several of them, so raw p-values would overstate significance.
Holm controls the family-wise error rate without assuming independence.

**Confidence intervals on the per-bucket numbers.** `high` has a few hundred
items at most; a margin reported without its interval invites a conclusion the
sample cannot support. Where the interval crosses zero, this says so.
"""

import argparse
import csv
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from scipy import stats
from sklearn.metrics import confusion_matrix, f1_score

from src.preprocess.textnorm import utf8_stdout

ROOT = Path(__file__).resolve().parents[2]
PRED = ROOT / "data" / "labeled" / "predictions.csv"

BUCKETS = ["mono", "low", "med", "high"]
LABELS = ["pos", "neg", "neu"]


def load(path):
    if not path.exists():
        raise SystemExit(
            "{} not found.\nRun: python -m src.models.run_cv".format(path))
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def mcnemar(a_correct, b_correct):
    """Exact McNemar on paired correctness. Returns (n01, n10, p).

    n01 = A wrong, B right; n10 = A right, B wrong. Only discordant pairs carry
    information, so the exact binomial is used rather than the chi-square
    approximation, which is unreliable when they are few - and here they will be.
    """
    n01 = sum(1 for x, y in zip(a_correct, b_correct) if not x and y)
    n10 = sum(1 for x, y in zip(a_correct, b_correct) if x and not y)
    n = n01 + n10
    if n == 0:
        return n01, n10, 1.0
    p = stats.binomtest(min(n01, n10), n, 0.5).pvalue
    return n01, n10, min(1.0, p)


def holm(pvals):
    """Holm-Bonferroni adjusted p-values, order preserved."""
    m = len(pvals)
    order = sorted(range(m), key=lambda i: pvals[i])
    adj, running = [0.0] * m, 0.0
    for rank, i in enumerate(order):
        running = max(running, (m - rank) * pvals[i])
        adj[i] = min(1.0, running)
    return adj


def wilson(k, n, z=1.96):
    """Wilson interval - behaves sensibly at the small n these buckets have."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    s = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5)
    return ((c - s) / d, (c + s) / d)


def section(title, w):
    w("")
    w("## " + title)
    w("")


def main():
    utf8_stdout()
    p = argparse.ArgumentParser()
    p.add_argument("--pred", default=str(PRED))
    p.add_argument("--out", help="also write the report to this markdown file")
    p.add_argument("--clf", default=None, help="restrict to one classifier")
    args = p.parse_args()

    rows = load(Path(args.pred))
    if args.clf:
        rows = [r for r in rows if r["classifier"] == args.clf]
    if not rows:
        raise SystemExit("No predictions matched.")

    by_rep = defaultdict(dict)          # rep -> comment_id -> row
    for r in rows:
        by_rep[r["representation"]][r["comment_id"]] = r
    reps = sorted(by_rep)
    common = set.intersection(*(set(d) for d in by_rep.values()))
    if not common:
        raise SystemExit("Representations share no comments - rerun run_cv.")
    ids = sorted(common)

    gold = {cid: by_rep[reps[0]][cid]["gold"] for cid in ids}
    dens = {cid: by_rep[reps[0]][cid]["density"] for cid in ids}

    lines = []
    w = lines.append
    w("# Representation comparison")
    w("")
    w("Generated by `src/eval/compare.py` from `{}`. {} comments, {} "
      "representations.".format(Path(args.pred).name, len(ids), len(reps)))

    # ---- H1: overall ---------------------------------------------------------
    section("Overall (H1)", w)
    w("Macro-F1 over the cross-validated predictions. Accuracy is shown only "
      "next to the majority-class floor it has to beat.")
    w("")
    floor = Counter(gold.values()).most_common(1)[0][1] / len(ids)
    w("Majority-class floor: **{:.3f}** accuracy (always predict `{}`).".format(
        floor, Counter(gold.values()).most_common(1)[0][0]))
    w("")
    w("| Representation | macro-F1 | accuracy | vs floor |")
    w("|---|---|---|---|")
    overall = {}
    for rep in reps:
        y = [gold[c] for c in ids]
        yh = [by_rep[rep][c]["pred"] for c in ids]
        f1 = f1_score(y, yh, average="macro", zero_division=0)
        acc = sum(a == b for a, b in zip(y, yh)) / len(y)
        overall[rep] = f1
        w("| {} | **{:.3f}** | {:.3f} | {:+.3f} |".format(rep, f1, acc, acc - floor))
    best = max(overall, key=overall.get)
    w("")
    w("Best overall: **{}** (macro-F1 {:.3f}).".format(best, overall[best]))

    # ---- H2 / H3: per bucket -------------------------------------------------
    section("By code-switching density (H2, H3)", w)
    w("Each bucket against its own majority-class floor - a bucket dominated by "
      "one class flatters every model in it.")
    w("")
    header = "| Bucket | n | floor | " + " | ".join(reps) + " |"
    w(header)
    w("|" + "---|" * (3 + len(reps)))
    per_bucket = defaultdict(dict)
    for b in BUCKETS:
        bids = [c for c in ids if dens[c] == b]
        if not bids:
            w("| {} | 0 | - | ".format(b) + " | ".join("-" for _ in reps) + " |")
            continue
        y = [gold[c] for c in bids]
        bfloor = Counter(y).most_common(1)[0][1] / len(y)
        cells = []
        for rep in reps:
            yh = [by_rep[rep][c]["pred"] for c in bids]
            f1 = f1_score(y, yh, average="macro", zero_division=0)
            per_bucket[b][rep] = f1
            cells.append("{:.3f}".format(f1))
        flag = " **(thin)**" if len(bids) < 100 else ""
        w("| {}{} | {} | {:.3f} | ".format(b, flag, len(bids), bfloor)
          + " | ".join(cells) + " |")

    w("")
    w("### Does the best representation's margin shrink with density? (H2)")
    w("")
    others = [r for r in reps if r != best]
    if others:
        w("| Bucket | n | {} | best of the rest | margin |".format(best))
        w("|---|---|---|---|---|")
        for b in BUCKETS:
            if b not in per_bucket or best not in per_bucket[b]:
                continue
            bids = [c for c in ids if dens[c] == b]
            rest = max((per_bucket[b][r] for r in others), default=0.0)
            w("| {} | {} | {:.3f} | {:.3f} | **{:+.3f}** |".format(
                b, len(bids), per_bucket[b][best], rest,
                per_bucket[b][best] - rest))
        w("")
        w("H2 predicts this margin falls from `mono` to `high`. Read it together "
          "with the bucket sizes - a margin computed on under ~100 items is not "
          "evidence in either direction.")

    # ---- significance --------------------------------------------------------
    section("Pairwise significance (McNemar, Holm-Bonferroni)", w)
    w("Paired on the same comments. `n01`/`n10` are the discordant counts - the "
      "only ones the test uses.")
    w("")
    tests = []
    for i, a in enumerate(reps):
        for bb in reps[i + 1:]:
            for scope in ["all"] + BUCKETS:
                sids = ids if scope == "all" else [c for c in ids if dens[c] == scope]
                if len(sids) < 20:
                    continue
                ac = [by_rep[a][c]["pred"] == gold[c] for c in sids]
                bc = [by_rep[bb][c]["pred"] == gold[c] for c in sids]
                n01, n10, pv = mcnemar(ac, bc)
                tests.append({"a": a, "b": bb, "scope": scope, "n": len(sids),
                              "n01": n01, "n10": n10, "p": pv})
    if tests:
        adj = holm([t["p"] for t in tests])
        w("| Comparison | Scope | n | n01 | n10 | p | p (Holm) | |")
        w("|---|---|---|---|---|---|---|---|")
        for t, pa in zip(tests, adj):
            mark = "**significant**" if pa < 0.05 else ""
            w("| {} vs {} | {} | {} | {} | {} | {:.4f} | {:.4f} | {} |".format(
                t["a"], t["b"], t["scope"], t["n"], t["n01"], t["n10"],
                t["p"], pa, mark))
        w("")
        w("{} of {} comparisons survive correction.".format(
            sum(1 for a in adj if a < 0.05), len(adj)))
    else:
        w("Not enough data for any pairwise test.")

    # ---- length control ------------------------------------------------------
    section("Length control", w)
    w("Short comments are harder for every model. If `high` comments are also "
      "systematically shorter, a drop there is length, not mixing - so the "
      "length distribution has to be on the table next to the H2 result.")
    w("")
    w("| Bucket | n | median tokens | mean |")
    w("|---|---|---|---|")
    for b in BUCKETS:
        lens = [int(by_rep[reps[0]][c]["n_tokens"]) for c in ids if dens[c] == b]
        if lens:
            w("| {} | {} | {:.0f} | {:.1f} |".format(
                b, len(lens), np.median(lens), np.mean(lens)))

    # ---- confusion matrix of the best ---------------------------------------
    section("Confusion matrix - {}".format(best), w)
    y = [gold[c] for c in ids]
    yh = [by_rep[best][c]["pred"] for c in ids]
    cm = confusion_matrix(y, yh, labels=LABELS)
    w("Rows = gold, columns = predicted.")
    w("")
    w("| | " + " | ".join(LABELS) + " |")
    w("|" + "---|" * (len(LABELS) + 1))
    for i, lab in enumerate(LABELS):
        w("| **{}** | ".format(lab) + " | ".join(str(x) for x in cm[i]) + " |")

    text = "\n".join(lines)
    print(text)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text + "\n", encoding="utf-8")
        print("\n-> {}".format(out))


if __name__ == "__main__":
    main()
